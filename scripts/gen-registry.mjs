// Finds every feature folder (a top-level folder containing feature.json) and writes src/registry.js,
// the static list the daemon imports. Static imports are what let the desktop app bundle everything
// into one file. Run `npm run features` after adding or removing a feature folder.
//   node scripts/gen-registry.mjs          write src/registry.js
//   node scripts/gen-registry.mjs --check  exit 1 if src/registry.js is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'registry.js');
const ID = /^[a-z0-9][a-z0-9-]{1,39}$/;

export function featureFolders() {
  return fs
    .readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(root, d.name, 'feature.json')))
    .map((d) => d.name)
    .sort();
}

export function render() {
  const lines = ['// GENERATED by scripts/gen-registry.mjs. Do not edit; run `npm run features`.'];
  const entries = [];
  featureFolders().forEach((dir, i) => {
    const manifest = JSON.parse(fs.readFileSync(path.join(root, dir, 'feature.json'), 'utf8'));
    if (manifest.id !== dir) throw new Error(`${dir}/feature.json: id "${manifest.id}" must match the folder name "${dir}"`);
    if (!ID.test(manifest.id)) throw new Error(`${dir}/feature.json: bad id`);
    const hasBackend = fs.existsSync(path.join(root, dir, 'index.js'));
    const hasUi = fs.existsSync(path.join(root, dir, 'ui', 'index.js'));
    if (hasBackend) lines.push(`import backend${i} from '../${dir}/index.js';`);
    entries.push(`  { manifest: ${JSON.stringify({ ...manifest, ui: hasUi })}, backend: ${hasBackend ? `backend${i}` : 'null'} },`);
  });
  return `${lines.join('\n')}\n\nexport const FEATURES = [\n${entries.join('\n')}\n];\n`;
}

// Only act when run as a script, not when another script imports render() or featureFolders().
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const next = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current !== next) {
      console.error('src/registry.js is out of date. Run: npm run features');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, next);
    console.log(`registry: ${featureFolders().join(', ') || '(none)'}`);
  }
}
